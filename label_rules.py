COMPILED = {
    "override": [(a, p, re.compile(rx)) for a, p, rx in OVERRIDE],
    "polar": [(a, p, re.compile(rx)) for a, p, rx in POLAR],
    "mention": [(a, re.compile(rx)) for a, rx in MENTION],
    "generic": [(p, re.compile(rx)) for p, rx in GENERIC],
}


def _take(rx, text):
    """매칭이 있으면 그 구간을 공백으로 지운 문자열과 True 를 돌려준다."""
    if rx.search(text):
        return rx.sub(" ", text), True
    return text, False


def classify_clause(clause, with_source=False):
    """절 하나의 (측면, 극성) 목록. with_source 면 (측면, 극성, 일반어에서 왔는가)."""
    found = []  # (측면, 극성)
    text = clause
    for aspect, pol, rx in COMPILED["override"]:
        text, hit = _take(rx, text)
        if hit and aspect:
            found.append((aspect, pol))
    for aspect, pol, rx in COMPILED["polar"]:
        text, hit = _take(rx, text)
        if hit:
            found.append((aspect, pol))
    mentioned = {aspect for aspect, rx in COMPILED["mention"] if rx.search(text)}
    generic = []
    for pol, rx in COMPILED["generic"]:
        text, hit = _take(rx, text)
        if hit:
            generic.append(pol)
    polar_aspects = {a for a, _ in found}
    targets = mentioned - polar_aspects
    specific = list(found)
    from_generic = []
    if generic:
        if not targets and not found:
            targets = {"taste"}
        for aspect in targets:
            for pol in generic:
                from_generic.append((aspect, pol))
    if with_source:
        return [(a, p, False) for a, p in specific] + [(a, p, True) for a, p in from_generic]
    return specific + from_generic


HEDGE = re.compile(r"좀|조금|약간|살짝|다소|빼고|빼면|제외|아쉬운\s*건|단점이라면")


def merge(votes):
    """절 단위 표를 모아 극성 하나로. 한쪽이 나머지의 두 배 이상이면 그 극성, 아니면 엇갈림.

    v2: 표는 (극성, 무게) 다. 「좀 짰어요」 처럼 누그러뜨린 절의 부정은 0.5 로 센다.
    """
    votes = [v if isinstance(v, tuple) else (v, 1.0) for v in votes]
    pos = sum(w for p, w in votes if p == "pos")
    neg = sum(w for p, w in votes if p == "neg")
    mixed = sum(w for p, w in votes if p == "mixed")
    if not votes:
        return "none"
    if pos and pos >= 2 * (neg + mixed):
        return "pos"
    if neg and neg >= 2 * (pos + mixed):
        return "neg"
    return "mixed"


def clauses(text):
    """절 목록. 쉼표 앞이 LIST_ITEM 자 이하면 나열 항목으로 보고 다음 조각과 잇는다."""
    out = []
    for part in SPLIT.split(text or ""):
        carry = ""
        for piece in COMMA.split(part):
            if len(piece.strip()) <= LIST_ITEM:
                carry += piece + " "
            else:
                out.append(carry + piece)
                carry = ""
        if carry.strip():
            out.append(carry)
    return out


def classify(text):
    per = {a: [] for a in ASPECTS}
    generic_taste_neg = []
    other_neg = False
    for clause in clauses(text):
        if clause.strip():
            weight = 0.5 if HEDGE.search(clause) else 1.0
            for aspect, pol, gen in set(classify_clause(clause, with_source=True)):
                vote = (pol, weight if pol == "neg" else 1.0)
                if aspect == "taste" and pol == "neg" and gen:
                    generic_taste_neg.append(vote)
                    continue
                if aspect != "taste" and pol == "neg" and not gen:
                    other_neg = True
                per[aspect].append(vote)
    # 코드북 규칙 8: 대상 없는 부정어가 맛 이외의 불만과 함께 있으면 그 불만에 대한 말로 읽는다
    if not other_neg:
        per["taste"].extend(generic_taste_neg)
    return {a: merge(per[a]) for a in ASPECTS}


